def measure(panel, colw):
    """Panel height (in) from its blocks."""
    inner = colw - 2 * PAD
    h = HDR_H + 0.25
    for b in panel["blocks"]:
        k = b[0]
        if k == "fig":
            from PIL import Image
            im = Image.open(b[1])
            h += b[2] * im.size[1] / im.size[0] + 0.28
        elif k == "cap":
            h += text_h(b[1], inner, SZ_CAP) + 0.20
        elif k == "body":
            h += text_h(b[1], inner, SZ_BODY) + 0.28
        elif k == "stats":
            h += 2.35 + 0.25
        elif k == "big":
            h += 1.5 + text_h(b[2], inner, SZ_CAP) + 0.35
        elif k == "mono":
            h += len(b[1].split("\n")) * SZ_MONO * 1.30 / 72.0 + 0.55
        elif k == "logos":
            h += max(ht for _, ht in b[1]) + 0.45
    return h + 0.30


def _col_end(panels, scale, colw):
    """Bottom edge of a column whose figures are scaled by `scale`."""
    y = TOP
    for p in panels:
        y += measure(_scaled(p, scale), colw) + GAP
    return y - GAP


def _scaled(panel, scale):
    """Panel with every figure width multiplied by `scale`."""
    if scale >= 1.0:
        return panel
    blocks = [(b[0], b[1], b[2] * scale) if b[0] == "fig" else b
              for b in panel["blocks"]]
    return dict(panel, blocks=blocks)


def layout(assets):
    """Assign (x, y, w, h) to every panel, shrinking figures to fit."""
    cols = build_panels(assets)
    placed, fits = [], []
    for ci, panels in enumerate(cols):
        # Largest scale in [0.72, 1.0] that keeps the column above BOTTOM.
        colw = CWS[ci]
        scale = 1.0
        while scale > 0.72 and _col_end(panels, scale, colw) > BOTTOM:
            scale -= 0.02
        fits.append(scale)
        y = TOP
        for p in panels:
            q = _scaled(p, scale)
            h = measure(q, colw)
            placed.append(dict(q, x=COLS[ci], y=y, w=colw, h=h, col=ci))
            y += h + GAP
    return placed, fits


# --- renderer 1: the editable .pptx -----------------------------------------
def render_pptx(panels, out):
    from pptx import Presentation
    from pptx.util import Inches, Pt
    from pptx.dml.color import RGBColor
    from pptx.enum.shapes import MSO_SHAPE
    from pptx.enum.text import PP_ALIGN, MSO_ANCHOR

    def rgb(h):
        return RGBColor(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))

    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(W), Inches(H)
    s = prs.slides.add_slide(prs.slide_layouts[6])

    def rect(x, y, w, h, fill, line=None, shape=MSO_SHAPE.RECTANGLE):
        sh = s.shapes.add_shape(shape, Inches(x), Inches(y), Inches(w),
                                Inches(h))
        sh.fill.solid()
        sh.fill.fore_color.rgb = rgb(fill)
        if line:
            sh.line.color.rgb = rgb(line)
            sh.line.width = Pt(1.0)
        else:
            sh.line.fill.background()
        sh.shadow.inherit = False
        return sh

    def text(x, y, w, h, s_, size, bold=False, color=INK, align=PP_ALIGN.LEFT,
             anchor=MSO_ANCHOR.TOP, mono=False, lead=None):
        tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
        tf = tb.text_frame
        tf.word_wrap = True
        tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
        tf.vertical_anchor = anchor
        for i, para in enumerate(s_.split("\n")):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.alignment = align
            if lead:
                p.line_spacing = lead
            r = p.add_run()
            r.text = para
            r.font.name = "Courier New" if mono else FONT
            r.font.size = Pt(size)
            r.font.bold = bold
            r.font.color.rgb = rgb(color)
        return tb

    # title band: title across the top, university logo left, authors centred
    rect(0.7, 0.3, W - 1.4, 4.35, BAND)
    text(1.2, 0.52, W - 2.4, 1.5,
         "BLADEI: Benchmark Validity and Placement-Aware Trojan "
         "Localization in FPGA Bitstreams", SZ_TITLE, True, INK,
         align=PP_ALIGN.CENTER)
    usc = os.path.join(LOGO_DIR, USC_LOGO)
    logo_w = 0.0
    if os.path.exists(usc):
        from PIL import Image
        im = Image.open(usc)
        lh = 2.15
        logo_w = lh * im.size[0] / im.size[1]
        s.shapes.add_picture(usc, Inches(1.15), Inches(2.20), height=Inches(lh))
    tx = 1.15 + logo_w + 0.8           # keeps the text clear of the logo
    text(0.7, 2.42, W - 1.4, 0.62,
         "Carter Antley  [ctantley@email.sc.edu]      •      "
         "Rasha Karakchi (advisor)  [karakchi@cec.sc.edu]", SZ_AUTH,
         align=PP_ALIGN.CENTER)
    text(0.7, 3.18, W - 1.4, 0.62,
         "Department of Computer Science and Engineering, University of "
         "South Carolina", SZ_AFF, False, MUTED, align=PP_ALIGN.CENTER)

    for p in panels:
        x, y, w, h = p["x"], p["y"], p["w"], p["h"]
        rect(x, y, w, h, PANEL, PANEL_EDGE)
        rect(x + PAD, y + 0.16, w - 2 * PAD, HDR_H, GARNET)
        text(x + PAD + 0.22, y + 0.16, w - 2 * PAD - 0.44, HDR_H,
             p["title"], SZ_HDR, True, "FFFFFF", anchor=MSO_ANCHOR.MIDDLE)
        cy = y + 0.16 + HDR_H + 0.25
        inner = w - 2 * PAD
        for b in p["blocks"]:
            k = b[0]
            if k == "fig":
                from PIL import Image
                im = Image.open(b[1])
                fh = b[2] * im.size[1] / im.size[0]
                s.shapes.add_picture(b[1], Inches(x + (w - b[2]) / 2),
                                     Inches(cy), width=Inches(b[2]))
                cy += fh + 0.28
            elif k == "cap":
                th = text_h(b[1], inner, SZ_CAP)
                text(x + PAD, cy, inner, th, b[1], SZ_CAP, False, MUTED)
                cy += th + 0.20
            elif k == "body":
                th = text_h(b[1], inner, SZ_BODY)
                text(x + PAD, cy, inner, th, b[1], SZ_BODY, False, INK,
                     lead=1.15)
                cy += th + 0.28
            elif k == "stats":
                n = len(b[1])
                cwid = (inner - 0.4 * (n - 1)) / n
                for i, (big, lbl) in enumerate(b[1]):
                    cx = x + PAD + i * (cwid + 0.4)
                    rect(cx, cy, cwid, 2.35, CARD)
                    text(cx + 0.25, cy + 0.18, cwid - 0.5, 1.05, big,
                         SZ_STAT, True, GARNET)
                    text(cx + 0.25, cy + 1.28, cwid - 0.5, 0.95, lbl,
                         SZ_STATLBL, False, INK)
                cy += 2.35 + 0.25
            elif k == "big":
                rect(x + PAD, cy, inner, 1.5, CARD)
                text(x + PAD + 0.3, cy + 0.2, inner - 0.6, 1.1, b[1],
                     54, True, GARNET)
                cy += 1.5 + 0.1
                th = text_h(b[2], inner, SZ_CAP)
                text(x + PAD, cy, inner, th, b[2], SZ_CAP, False, MUTED)
                cy += th + 0.25
            elif k == "mono":
                nl = len(b[1].split("\n"))
                bh = nl * SZ_MONO * 1.30 / 72.0 + 0.45
                rect(x + PAD, cy, inner, bh, CARD)
                text(x + PAD + 0.28, cy + 0.22, inner - 0.56, bh - 0.44,
                     b[1], SZ_MONO, False, INK, mono=True, lead=1.28)
                cy += bh + 0.10
            elif k == "logos":
                from PIL import Image
                items = []
                for path, ht in b[1]:
                    im = Image.open(path)
                    items.append((path, ht, ht * im.size[0] / im.size[1]))
                gapl = 1.1
                tot = sum(w_ for _, _, w_ in items) + gapl * (len(items) - 1)
                lx = x + PAD + (inner - tot) / 2.0
                band_h = max(ht for _, ht, _ in items)
                for path, ht, w_ in items:
                    s.shapes.add_picture(path,
                                         Inches(lx),
                                         Inches(cy + (band_h - ht) / 2.0),
                                         height=Inches(ht))
                    lx += w_ + gapl
                cy += band_h + 0.45
    prs.save(out)
    return out


