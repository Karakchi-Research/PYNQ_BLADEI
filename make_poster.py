def main():
    ap = argparse.ArgumentParser(description="Build the SC26 SRC poster")
    ap.add_argument("--assets", default="poster_assets")
    ap.add_argument("--out", default="BLADEI_SC26_SRC_poster.pptx")
    ap.add_argument("--proof", default="poster_proof.png")
    args = ap.parse_args()

