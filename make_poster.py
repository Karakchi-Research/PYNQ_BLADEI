def wrap_lines(text, width_in, size_pt):
    """Approximate wrapped line count/lines for Arial at size_pt in width_in."""
    cpi = 72.0 / (0.52 * size_pt)          # chars per inch, Arial average
    ncols = max(8, int(width_in * cpi))
    out = []
    for para in text.split("\n"):
        out.extend(textwrap.wrap(para, ncols) or [""])
    return out


def text_h(text, width_in, size_pt, lead=1.22):
    """Height (in) a wrapped text block needs."""
    return len(wrap_lines(text, width_in, size_pt)) * size_pt * lead / 72.0


